import { DID_KEY_ASSOCIATOR_OAUTH_SCOPE, OAUTH_SCOPE_LOCALHOST } from "@publicdomainrelay/oauth-scope";

const ROOT = import.meta.dirname;
const DIST = ROOT + "/dist";
const GENERATED_DIR = ROOT + "/generated";

try { await Deno.mkdir(DIST, { recursive: true }); } catch { /* exists */ }

// 1. Regenerate the committed browser-scope module from the single source
//    (typescript-helpers/lib/oauth-scope). The browser JS files import this
//    module; build.ts rewrites it on every build so the dev-mode source copy
//    and the deployed bundle can't drift from the package.
const generatedPath = `${GENERATED_DIR}/oauth-scope.js`;
const generated = [
  "// AUTO-GENERATED by build.ts from @publicdomainrelay/oauth-scope — DO NOT EDIT.",
  "// Single source: typescript-helpers/lib/oauth-scope/mod.ts. Regenerated on every build.",
  `export const OAUTH_SCOPE_FULL = ${JSON.stringify(DID_KEY_ASSOCIATOR_OAUTH_SCOPE.join(" "))};`,
  `export const OAUTH_SCOPE_LOCALHOST = ${JSON.stringify(OAUTH_SCOPE_LOCALHOST)};`,
  "",
].join("\n");
try {
  const existing = await Deno.readTextFile(generatedPath);
  if (existing !== generated) {
    console.error("generated/oauth-scope.js out of sync with @publicdomainrelay/oauth-scope — regenerated; commit the change");
    await Deno.writeTextFile(generatedPath, generated);
    Deno.exit(1);
  }
} catch {
  // First run — write the file, keep going.
  await Deno.writeTextFile(generatedPath, generated);
}

const bundleCmd = new Deno.Command("deno", {
  args: [
    "bundle", "--platform", "browser", "--minify",
    "--sourcemap=external", "--outdir", DIST,
    "components/dka-app.js",
  ],
  stdout: "inherit", stderr: "inherit",
});
const bundleStatus = await bundleCmd.output();
if (!bundleStatus.success) Deno.exit(bundleStatus.code);

// 2. Static assets. oauth-client-metadata.json scope is injected from the
//    oauth-scope package — the source file carries no scope field.
await Deno.copyFile(`${ROOT}/styles.css`, `${DIST}/styles.css`);
const metadata = JSON.parse(
  await Deno.readTextFile(`${ROOT}/oauth-client-metadata.json`),
) as Record<string, unknown>;
metadata.scope = DID_KEY_ASSOCIATOR_OAUTH_SCOPE.join(" ");
await Deno.writeTextFile(
  `${DIST}/oauth-client-metadata.json`,
  JSON.stringify(metadata, null, 2) + "\n",
);

const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="referrer" content="origin-when-cross-origin">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="Associate did:key cryptographic identifiers with your AT Protocol account. Public attestation, not access grant.">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700;800&family=IBM+Plex+Mono:wght@400;500;600&display=swap" rel="stylesheet">
  <link rel="stylesheet" href="./styles.css">
  <title>DID Key Associator</title>
</head>
<body>
  <dka-app></dka-app>
  <script type="module" src="./dka-app.js?v=${Date.now()}"></script>
</body>
</html>
`;
await Deno.writeTextFile(`${DIST}/index.html`, html);

console.log("Build complete → dist/");
